-- Stock opname: items, weekly count sessions, and one line per item per session.
-- Quantities are stored as the text staff typed ("3, 3/4", "5, 329 gr") and parsed in the app,
-- so nothing written on the floor is lost if a unit or pack size is set later.

create type item_category as enum ('Packaging', 'Bar', 'Dapur');

create table items (
  id bigint generated by default as identity primary key,
  name text not null,
  category item_category not null,
  unit text not null default '',
  pack_size numeric,
  pack_unit text not null default 'gr' check (pack_unit in ('gr', 'ml')),
  min_stock numeric,
  sort_order int not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table opname_sessions (
  id uuid primary key default gen_random_uuid(),
  count_date date not null,
  note text not null default '',
  created_by uuid references auth.users (id),
  created_at timestamptz not null default now()
);

create table opname_lines (
  session_id uuid not null references opname_sessions (id) on delete cascade,
  item_id bigint not null references items (id),
  awal text,
  masuk text,
  tersedia text,
  updated_by uuid references auth.users (id),
  updated_at timestamptz not null default now(),
  primary key (session_id, item_id)
);

create index opname_sessions_date_idx on opname_sessions (count_date desc);

-- Every signed-in account is cafe staff. Accounts are created by the owner in Supabase Auth.
alter table items enable row level security;
alter table opname_sessions enable row level security;
alter table opname_lines enable row level security;

create policy "staff read items" on items for select to authenticated using (true);
create policy "staff write items" on items for all to authenticated using (true) with check (true);
create policy "staff read sessions" on opname_sessions for select to authenticated using (true);
create policy "staff write sessions" on opname_sessions for all to authenticated using (true) with check (true);
create policy "staff read lines" on opname_lines for select to authenticated using (true);
create policy "staff write lines" on opname_lines for all to authenticated using (true) with check (true);
