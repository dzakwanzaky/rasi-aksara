-- Change log: who changed what, and when (Zaky, 12 Okt 2026).
-- Written by database triggers, so every change is caught whatever page made it.
-- Staff can read it but cannot edit or delete it.

create table audit_log (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  user_id uuid,
  user_email text,
  table_name text not null,
  action text not null,           -- INSERT, UPDATE, DELETE
  row_key text not null,
  old jsonb,
  new jsonb
);

create index audit_log_at_idx on audit_log (at desc);
create index audit_log_row_idx on audit_log (row_key, at desc);

alter table audit_log enable row level security;
create policy "staff read log" on audit_log for select to authenticated using (true);

create or replace function write_audit_log() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  claims jsonb := nullif(current_setting('request.jwt.claims', true), '')::jsonb;
  uid uuid := nullif(claims ->> 'sub', '')::uuid;
  email text := claims ->> 'email';
  o jsonb := case when tg_op <> 'INSERT' then to_jsonb(old) end;
  n jsonb := case when tg_op <> 'DELETE' then to_jsonb(new) end;
  key text;
  recent bigint;
begin
  if tg_table_name = 'opname_lines' then
    key := 'line:' || coalesce(new.session_id, old.session_id) || ':' || coalesce(new.item_id, old.item_id);
    -- Lines removed together with their count are recorded on the count itself.
    if tg_op = 'DELETE' and not exists (select 1 from opname_sessions where id = old.session_id) then return old; end if;
    -- Carrying yesterday's stock into a new count is recorded as "started the count".
    if tg_op = 'INSERT' and new.tersedia is null and new.masuk is null then return new; end if;
    o := o - 'updated_at' - 'updated_by';
    n := n - 'updated_at' - 'updated_by';
  elsif tg_table_name = 'opname_sessions' then
    key := 'session:' || coalesce(new.id, old.id);
    if tg_op = 'DELETE' then
      o := o || jsonb_build_object('lines',
        (select coalesce(jsonb_agg(to_jsonb(l) - 'updated_at' - 'updated_by'), '[]') from opname_lines l where l.session_id = old.id));
    end if;
  else
    key := 'item:' || coalesce(new.id, old.id);
  end if;

  if tg_op = 'UPDATE' and o = n then return new; end if;

  -- Autosave writes while staff type; fold one person's edits to the same row within 10 minutes into one entry.
  if tg_op = 'UPDATE' then
    select id into recent from audit_log
    where row_key = key and action in ('INSERT', 'UPDATE') and user_id is not distinct from uid
      and at > now() - interval '10 minutes'
    order by at desc limit 1;
    if recent is not null then
      update audit_log set new = n, at = now() where id = recent;
      return new;
    end if;
  end if;

  insert into audit_log (user_id, user_email, table_name, action, row_key, old, new)
  values (uid, email, tg_table_name, tg_op, key, o, n);
  return coalesce(new, old);
end $$;

create trigger audit_items after insert or update or delete on items
  for each row execute function write_audit_log();
create trigger audit_sessions_change after insert or update on opname_sessions
  for each row execute function write_audit_log();
-- Before delete, so the count's lines can still be copied into the log.
create trigger audit_sessions_delete before delete on opname_sessions
  for each row execute function write_audit_log();
create trigger audit_lines after insert or update or delete on opname_lines
  for each row execute function write_audit_log();
