-- Penjualan vs stok opname (Zaky, 20 Okt 2026).
-- Menu names as Majoo writes them, their recipes per portion, and the daily sales uploaded from Majoo's
-- "Detail Penjualan" export. The app compares what the recipes say was used with what the stock count says.
-- Safe to run again: it refreshes the rules and only adds menus and recipe lines that are not there yet.

create table if not exists menus (
  id bigint generated by default as identity primary key,
  name text not null unique,            -- exactly as in Majoo, e.g. 'Teh tarik', 'Rasi Nara'
  price int,                            -- Majoo price; used to work out portions per transaction
  created_at timestamptz not null default now()
);

-- qty is written like a stock count ("100 gr", "30 ml", "1", "1/2 pack") and read in the item's counting unit.
-- Grams for an item counted per potong/bungkus need that item's "isi per kemasan" (page Bahan).
create table if not exists recipe_lines (
  menu_id bigint not null references menus (id) on delete cascade,
  item_id bigint not null references items (id),
  qty text not null,
  primary key (menu_id, item_id)
);

create table if not exists sales_days (
  sale_date date primary key,
  file_name text,
  trx_count int not null default 0,
  total bigint not null default 0,
  uploaded_by_name text,
  uploaded_at timestamptz not null default now()
);

create table if not exists sales_lines (
  sale_date date not null references sales_days (sale_date) on delete cascade,
  menu text not null,
  shift text not null default '',       -- '1', '2', or '' when Majoo has no shift
  qty int not null,
  guessed int not null default 0,       -- portions from a transaction whose count could not be pinned down
  primary key (sale_date, menu, shift)
);

alter table menus enable row level security;
alter table recipe_lines enable row level security;
alter table sales_days enable row level security;
alter table sales_lines enable row level security;

-- Only admins (the owner) see and change sales and recipes.
drop policy if exists "admins menus" on menus;
create policy "admins menus" on menus for all to authenticated using (is_admin()) with check (is_admin());
drop policy if exists "admins recipe" on recipe_lines;
create policy "admins recipe" on recipe_lines for all to authenticated using (is_admin()) with check (is_admin());
drop policy if exists "admins sales days" on sales_days;
create policy "admins sales days" on sales_days for all to authenticated using (is_admin()) with check (is_admin());
drop policy if exists "admins sales lines" on sales_lines;
create policy "admins sales lines" on sales_lines for all to authenticated using (is_admin()) with check (is_admin());

